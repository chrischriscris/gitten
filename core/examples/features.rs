//! The feature map: every command, its keys, and where each client answers it.
//!
//!   ./dev features            writes docs/features.md
//!   cargo run -q -p gitten-core --example features
//!
//! A command is a name, so "where is X implemented" has a mechanical answer:
//! the file in each client that spells the name. Files and not lines,
//! because a line number would make the map stale on every edit. That is what an agent needs
//! first and what nobody keeps up to date by hand, so it is generated. It is
//! read from the registry and the shipped keymap, never from a list kept here,
//! so a command that exists is in the map and one that does not is not.
//!
//! "Answered" means the name appears as a string literal in that client's
//! source, outside its test module. A client that routes a whole namespace
//! through a prefix match, or builds a name with `format!`, shows as `—` even
//! though it answers; the map is a place to start reading, not a contract.
use gitten_core::command::{chord_string, Commands, Keymap};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

const CLIENTS: [(&str, &str); 3] = [("gui", "gui/src"), ("tui", "tui/src"), ("web", "web/src")];

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let commands = Commands::builtin();
    let keymap = Keymap::builtin();
    let sources: Vec<(&str, Vec<(String, String)>)> = CLIENTS
        .iter()
        .map(|&(name, dir)| (name, read_sources(&root, dir)))
        .collect();

    let mut out = String::new();
    out.push_str(
        "# Feature map\n\n\
         Generated by `./dev features` from `Commands::builtin()` and \
         `Keymap::builtin()` in `core/src/command.rs`. Do not edit it by hand; \
         `./check.sh` fails when it is stale.\n\n\
         Every command, the keys the shipped keymap binds to it (`mode: chord`), \
         whether it writes to the repository, and the first file in each client \
         that spells its name; grep it for the quoted name to land on the line. `—` means the name is not written as a literal \
         there: either the client does not answer it, or it reaches it through a \
         prefix match or a built name. Read the line before trusting the dash. \
         The desktop answers only arrows, Tab, Enter, Esc and `cmd-` chords from \
         the keyboard, so for `gui` the keys column is what the terminal does.\n",
    );

    // Grouped by namespace, in the order the registry first names each one;
    // the registry itself interleaves them, which is its business.
    let mut groups: Vec<(&str, String)> = Vec::new();
    for c in commands.all() {
        let ns = c.name.split_once('.').map_or("app", |(ns, _)| ns);
        let at = match groups.iter().position(|(g, _)| *g == ns) {
            Some(at) => at,
            None => {
                groups.push((ns, String::new()));
                groups.len() - 1
            }
        };
        let keys: Vec<String> = keymap
            .bindings()
            .iter()
            .filter(|b| b.command == c.name)
            .map(|b| code(&format!("{}: {}", b.mode, chord_string(&b.chord))))
            .collect();
        let needle = format!("\"{}\"", c.name);
        let found: Vec<String> = sources
            .iter()
            .map(|(_, files)| first_hit(files, &needle).unwrap_or_else(|| "—".into()))
            .collect();
        let _ = writeln!(
            groups[at].1,
            "| `{}` | {} | {} | {} | {} | {} | {} |",
            c.name,
            cell(&keys.join(", ")),
            if c.mutates { "yes" } else { "" },
            found[0],
            found[1],
            found[2],
            cell(&c.doc),
        );
    }
    for (ns, rows) in groups {
        let _ = write!(
            out,
            "\n## {ns}\n\n| command | keys | writes | gui | tui | web | does |\n|---|---|---|---|---|---|---|\n{rows}"
        );
    }
    print!("{out}");
}

/// Each `.rs` file under `dir`, relative to the repo root, cut at its test
/// module: a test that spells a name is not the client answering it.
fn read_sources(root: &Path, dir: &str) -> Vec<(String, String)> {
    let mut files = Vec::new();
    let mut stack = vec![root.join(dir)];
    while let Some(d) = stack.pop() {
        let Ok(entries) = std::fs::read_dir(&d) else {
            continue;
        };
        let mut paths: Vec<PathBuf> = entries.flatten().map(|e| e.path()).collect();
        paths.sort();
        for p in paths {
            if p.is_dir() {
                stack.push(p);
            } else if p.extension().is_some_and(|e| e == "rs") {
                let bytes = std::fs::read(&p).unwrap_or_default();
                let text = String::from_utf8_lossy(&bytes);
                let body = match text.find("\n#[cfg(test)]") {
                    Some(at) => &text[..at],
                    None => &text,
                };
                let rel = p.strip_prefix(root).unwrap_or(&p).display().to_string();
                files.push((rel, body.to_string()));
            }
        }
    }
    files.sort();
    files
}

fn first_hit(files: &[(String, String)], needle: &str) -> Option<String> {
    files.iter().find_map(|(path, body)| {
        body.contains(needle).then(|| {
            let name = path.split_once("/src/").map_or(path.as_str(), |(_, n)| n);
            format!("[{name}](../{path})")
        })
    })
}

/// A code span, wide enough for a key that is itself a backtick.
fn code(s: &str) -> String {
    if s.contains('`') {
        format!("`` {s} ``")
    } else {
        format!("`{s}`")
    }
}

/// A table cell: a pipe would end it early.
fn cell(s: &str) -> String {
    s.replace('|', "\\|")
}
